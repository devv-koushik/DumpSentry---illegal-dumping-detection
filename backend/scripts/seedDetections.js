// ─── Main ─────────────────────────────────────────────────────────────────────

async function main() {
  console.log("[Seed] Connecting to MongoDB...");
  await mongoose.connect(env.mongoUri, { serverSelectionTimeoutMS: 5000 });
  console.log("[Seed] Connected.");

  const existing = await Detection.countDocuments();
  if (existing > 0) {
    console.log(`[Seed] ${existing} detections already exist. Skipping seed.`);
    console.log("[Seed] To re-seed, drop the detections collection first.");
  } else {
    console.log(`[Seed] Inserting ${DEMO_DETECTIONS.length} demo detections...`);
    await Detection.insertMany(DEMO_DETECTIONS);
    console.log(`[Seed] ✓ Inserted ${DEMO_DETECTIONS.length} demo detections successfully.`);
  }

  await mongoose.disconnect();
  console.log("[Seed] Done.");
  process.exit(0);
}

main().catch((err) => {
  console.error("[Seed] Fatal error:", err.message);
  process.exit(1);
});
